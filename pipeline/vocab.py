"""Build the vocabulary: common English words that WordNet knows as a noun, verb or adjective, with their senses.

    .venv/Scripts/python -m pipeline.vocab [--size 15000]   ->  data/vocab.json, data/vocab_rejected.json

Each entry: {w, zipf, senses: [{pos, lex, count, def, syn, hyper, ex}]}, most used sense first (SemCor count, then
WordNet's order), at most 6.
Filters, in order (the reason is recorded in vocab_rejected.json):
  shape     a-z only, 3+ letters
  stopword  NLTK English stopwords ("have", "will", "can" are WordNet nouns too, but useless as guesses)
  blocklist data/blocklist-ldnoobw.txt (LDNOOBW, CC BY 4.0) + data/blocklist-extra.txt
  no-lemma  WordNet has no noun/verb/adjective sense whose lemma is exactly this word in lowercase
            (drops inflections like "dogs", and proper nouns like "london")
  offensive every remaining sense is offensive, or the most common one is (see is_offensive)
Offensive senses of kept words are dropped too, so they never reach a definition vector.
"""
import argparse
import json
import pathlib
import re

from nltk.corpus import stopwords
from nltk.corpus import wordnet as wn
from wordfreq import top_n_list, zipf_frequency

DATA = pathlib.Path("data")
POS = {"n": "n", "v": "v", "a": "a", "s": "a"}  # satellite adjectives count as adjectives
OFFENSIVE_DOMAINS = {"ethnic_slur.n.01", "obscenity.n.02", "disparagement.n.01", "vulgarism.n.01"}
# How WordNet glosses label an offensive *term* ("offensive term for…", "(vulgar) …"). Plain "offensive" is too broad:
# it would drop "attack" ("an offensive against an enemy") and "disgusting" ("highly offensive").
OFFENSIVE_WORDS = re.compile(
    r"\b(offensive|derogatory|disparaging|contemptuous|vulgar|obscene)\s+(term|name|word|slang|expression)\b"
    r"|\((ethnic )?slur\b|\(vulgar|\(offensive|\(derogatory|\(obscene", re.I)


def blocklist():
    words = set()
    for name in ("blocklist-ldnoobw.txt", "blocklist-extra.txt"):
        p = DATA / name
        if p.exists():
            for line in p.read_text(encoding="utf-8").splitlines():
                line = line.strip().lower()
                if line and not line.startswith("#"):
                    words.add(line)
    return words


def is_offensive(syn):
    if any(d.name() in OFFENSIVE_DOMAINS for d in syn.usage_domains()):
        return True
    return bool(OFFENSIVE_WORDS.search(syn.definition()))


def senses_of(w):
    """WordNet senses whose lemma is exactly w (lowercase, so not a proper noun), most common first."""
    out = []
    for s in wn.synsets(w):
        if s.pos() not in POS:
            continue
        if not any(l.name() == w for l in s.lemmas()):
            continue
        out.append(s)
    return out


def sense_record(s, w):
    hypers = s.hypernyms() or s.instance_hypernyms()
    return {
        "pos": POS[s.pos()],
        "lex": s.lexname(),
        # How often this sense of w was tagged in WordNet's SemCor corpus (0 for most rare senses).
        "count": sum(l.count() for l in s.lemmas() if l.name() == w),
        "def": s.definition(),
        "syn": [l.name().replace("_", " ") for l in s.lemmas() if l.name() != w][:4],
        "hyper": [h.lemmas()[0].name().replace("_", " ") for h in hypers][:2],
        "ex": s.examples()[:2],
    }


def build(size):
    stop = set(stopwords.words("english"))
    block = blocklist()
    kept, rejected = [], {}
    for w in top_n_list("en", 100000):
        if len(kept) >= size:
            break
        reason = None
        if not re.fullmatch(r"[a-z]{3,}", w):
            reason = "shape"
        elif w in stop:
            reason = "stopword"
        elif w in block:
            reason = "blocklist"
        else:
            syns = senses_of(w)
            if not syns:
                reason = "no-lemma"
            elif is_offensive(syns[0]) or all(is_offensive(s) for s in syns):
                reason = "offensive"
            else:
                # Most used first. WordNet lists every noun sense before the verbs and adjectives, so its order
                # alone would put "straight" (poker hand) ahead of "straight" (no bends). Ties keep WordNet's order.
                senses = [sense_record(s, w) for s in syns if not is_offensive(s)]
                senses.sort(key=lambda r: -r["count"])
                kept.append({"w": w, "zipf": zipf_frequency(w, "en"), "senses": senses[:6]})
        if reason and reason != "shape":
            rejected.setdefault(reason, []).append(w)
    return kept, rejected


def irregular_forms(words):
    """base -> irregular inflections (mouse -> mice, go -> went/gone, good -> better/best), from WordNet's
    exception lists, for the given words only. Regular forms are generated by site/js/ban.js."""
    wn.ensure_loaded()
    out = {}
    for pos in ("n", "v", "a"):
        for form, bases in wn._exception_map[pos].items():
            if not re.fullmatch(r"[a-z]+", form):
                continue
            for b in bases:
                if b in words and form != b:
                    out.setdefault(b, set()).add(form)
    return {b: sorted(f) for b, f in sorted(out.items())}


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--size", type=int, default=15000)
    args = ap.parse_args()
    kept, rejected = build(args.size)
    irregular = irregular_forms({e["w"] for e in kept})
    (DATA / "irregular.json").write_text(json.dumps(irregular), encoding="utf-8")
    print(f"irregular forms for {len(irregular)} words, e.g. mouse={irregular.get('mouse')}, go={irregular.get('go')}")
    (DATA / "vocab.json").write_text(json.dumps(kept, ensure_ascii=False), encoding="utf-8")
    (DATA / "vocab_rejected.json").write_text(json.dumps(rejected, indent=0), encoding="utf-8")
    print(f"{len(kept)} words (zipf {kept[-1]['zipf']:.2f} and up), {sum(len(e['senses']) for e in kept)} senses")
    for k, v in rejected.items():
        print(f"  rejected {k}: {len(v)}  e.g. {', '.join(v[:12])}")
