// Compile tools/score.wat into site/js/score.wasm.js (base64 inlined, so no extra request or MIME setup).
//   node tools/build-wasm.mjs
import fs from 'node:fs';
import wabtInit from 'wabt';

const wabt = await wabtInit();
const mod = wabt.parseWat('score.wat', fs.readFileSync('tools/score.wat', 'utf8'), { simd: true });
const { buffer } = mod.toBinary({});
fs.writeFileSync('site/js/score.wasm.js',
  `// Generated by tools/build-wasm.mjs from tools/score.wat. Don't edit.\nexport const SCORE_WASM = '${Buffer.from(buffer).toString('base64')}';\n`);
console.log(`site/js/score.wasm.js: ${buffer.length} bytes of wasm`);
